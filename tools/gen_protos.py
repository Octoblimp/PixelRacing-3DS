#!/usr/bin/env python3
"""Generate 3DS Files/include/protos.h: one C prototype per iOS game function.

Sources: Ghidra's declaration (decomp/raw/c/<addr>_<name>.c, for parameter count and pointer-ness)
and decomp/signatures.tsv (tools/disasm.py, softfp float hints). Every translated function must
use exactly the prototype here, so modules translated separately link together. Fixes go into
OVERRIDES below (with the reason) and the header is regenerated.

Conventions: integer-ish -> int, pointers -> void *, floats -> float. Names are fn_<addr>; a
known role is given in the trailing comment (from decomp/symbols.csv).
"""
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# addr -> full prototype text (without the trailing ';'), when the heuristics are wrong.
OVERRIDES = {
    # sys/engine helpers verified by hand
    "00004fb4": "void fn_00004fb4(int r, int g, int b, int a)",           # glColor4f(x/255)
    "00005008": "void fn_00005008(unsigned rgba)",                         # glColor4f from packed
    "00005ac4": "void fn_00005ac4(int render)",                            # game tick (state machine)
    "000055f8": "void *fn_000055f8(int size)",                             # CxAlloc32Mem1
    "00005654": "void fn_00005654(void *p)",                               # CxFree
}

SKIP_CLASSES = {"platform-objc"}


def module_overrides():
    """decomp/protos/<module>.tsv: 'addr<TAB>prototype' lines written by each module's translator
    for the functions that module defines (the definition is the authority)."""
    out = {}
    d = os.path.join(ROOT, "decomp", "protos")
    for f in sorted(glob.glob(os.path.join(d, "*.tsv"))):
        for line in open(f, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            addr, proto = line.split("	", 1)
            out[addr.strip().lower().rjust(8, "0")] = proto.strip().rstrip(";")
    return out


def ghidra_decl(addr):
    fs = glob.glob(os.path.join(ROOT, "decomp", "raw", "c", addr + "_*.c"))
    if not fs:
        return None
    txt = open(fs[0], encoding="utf-8", errors="replace").read()
    m = re.search(r"^([^\n{;]*?)\b(FUN_[0-9a-f]+|[A-Za-z_][\w:]*)\s*\(([^)]*)\)\s*\{", txt, re.M | re.S)
    if not m:
        return None
    ret = m.group(1).replace("__stdcall_softfp", "").replace("__stdcall", "").strip()
    params = [p.strip() for p in m.group(3).split(",") if p.strip() and p.strip() != "void"]
    return ret, params


def ctype(gt):
    gt = gt.strip()
    if "*" in gt:
        return "void *"
    if gt in ("float",):
        return "float"
    if gt in ("double", "undefined8", "longlong", "ulonglong"):
        return "long long"
    return "int"


def main():
    syms = {r["addr"]: r for r in csv.DictReader(open(os.path.join(ROOT, "decomp", "symbols.csv")))}
    sigs = {r["addr"]: r for r in csv.DictReader(open(os.path.join(ROOT, "decomp", "signatures.tsv")),
                                                 delimiter="\t")}
    OVERRIDES.update(module_overrides())
    out = ["/* Generated by tools/gen_protos.py -- do not edit; fixes go in decomp/protos/<module>.tsv. */",
           "#pragma once", ""]
    for addr in sorted(syms):
        s = syms[addr]
        if s["class"] in SKIP_CLASSES:
            continue
        role = s["name"] if not s["name"].startswith("FUN_") else ""
        if s.get("notes"):
            role = (role + " " + s["notes"]).strip()
        if addr in OVERRIDES:
            out.append(OVERRIDES[addr] + ";" + (f" /* {role} */" if role else ""))
            continue
        g = ghidra_decl(addr)
        sg = sigs.get(addr, {})
        fregs = set(filter(None, (sg.get("float_params") or "").split(",")))
        if g:
            gret, gparams = g
            types = [ctype(p if "*" in p else (p.rsplit(" ", 1)[0] if " " in p else p)) for p in gparams]
        else:
            gret, types = "void", ["int"] * int(sg.get("nparams") or 0)
        for i in range(min(4, len(types))):
            if f"r{i}" in fregs and types[i] == "int":
                types[i] = "float"
        ret = ctype(gret) if gret not in ("void",) else "void"
        if int(sg.get("ret_float_callers") or 0) > 0 or gret == "float":
            ret = "float"
        params = ", ".join(f"{t}{'' if t.endswith('*') else ' '}p{i + 1}" for i, t in enumerate(types)) or "void"
        sp = "" if ret.endswith("*") else " "
        out.append(f"{ret}{sp}fn_{addr}({params});" + (f" /* {role} */" if role else ""))
    # functions Ghidra missed (found later, e.g. 0x35fdc sound init): only in an override file
    extra = sorted(a for a in OVERRIDES if a not in syms)
    if extra:
        out.append("")
        out.append("/* not in symbols.csv (missed by Ghidra's function discovery) */")
        out += [OVERRIDES[a] + ";" for a in extra]
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "3DS Files", "include", "protos.h")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote", path, len(out) - 3, "prototypes")


if __name__ == "__main__":
    main()
